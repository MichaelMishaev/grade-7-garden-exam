import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import snapshot from '../content-snapshot.js';
import {createState} from '../core.js';
import {normalizeMazeContent} from '../content.js';

const base = process.env.MAZE_QA_URL || 'http://127.0.0.1:4328/games/maze/play/index.html';
const output = fileURLToPath(new URL('../../../output/maze/cage-critic/', import.meta.url));
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const checks=[],errors=[],posts=[];
const read=page=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
const stable=value=>JSON.stringify({player:value.player,hearts:value.hearts,coins:value.coins,seals:value.seals,progress:value.progress,current:value.currentQuestion?.id});
const check=(name,value)=>{assert.ok(value,name);checks.push(name);console.log(`PASS ${name}`);};
let page;
try {
  const context=await browser.newContext({viewport:{width:844,height:390},isMobile:true,hasTouch:true});
  await context.route('**/api/quizzes/**',route=>route.abort());
  context.on('request',req=>{if(req.method()==='POST')posts.push(req.url());});
  context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  page=await context.newPage();await page.goto(base);await page.locator('#start-button').click();
  for(const dir of ['down','down','down','down','right','right','right']){await page.locator(`[data-direction="${dir}"]`).click();await page.evaluate(()=>window.advanceTime(900));}
  const before=await read(page);check('real movement enters a capped first-person trap',before.phase==='question'&&before.view==='first-person-cage'&&before.encounters.every(e=>e.questions>=1&&e.questions<=3));
  const bounds=await page.evaluate(()=>{const c=document.querySelector('#maze-canvas').getBoundingClientRect(),d=document.querySelector('#game-dialog').getBoundingClientRect();return{canvas:{left:c.left,right:c.right,top:c.top,bottom:c.bottom},dialog:{left:d.left,right:d.right,top:d.top,bottom:d.bottom}};});
  await page.screenshot({path:`${output}/landscape-cage.png`,fullPage:true});
  check('landscape question sheet leaves the first-person cage unobscured beside it',bounds.canvas.right<=bounds.dialog.left-8);
  for(const action of ['look-left','look-right','lantern','rattle','inspect'])await page.locator(`[data-cell-action="${action}"]`).click();
  check('landscape scene controls cannot change academic progress or move the player',stable(await read(page))===stable(before));
  await page.setViewportSize({width:320,height:568});
  const choice=page.locator('[data-choice]').last();await choice.scrollIntoViewIfNeeded();
  check('short portrait phone can scroll to the last answer',await choice.isVisible()&&await choice.isEnabled());
  await page.screenshot({path:`${output}/short-portrait-cage.png`,fullPage:true});
  const original=snapshot.quizzes.flatMap(q=>q.questions).find(q=>q.id===before.currentQuestion.id);
  await page.locator(`[data-choice="${original.correct}"]`).click();
  await page.locator('[data-cell-action="inspect"]').click();
  const feedback=await read(page);await page.waitForTimeout(1800);
  check('inspect in feedback freezes advancement without duplicate coin rewards',(await read(page)).phase==='feedback'&&(await read(page)).coins===10);
  await page.locator('#encounter-menu').click();await page.locator('#resume-button').click();
  check('pause and resume preserve the locked first answer and coins',stable(await read(page))===stable(feedback));
  await page.reload();await page.locator('#start-button').click();await page.locator('#read-feedback').click();
  check('reload preserves locked feedback, trap progress and its single payout',stable(await read(page))===stable(feedback));
  await page.locator('#continue-button').click();
  check('explicit continue reaches the next original question without a fourth trap question',(await read(page)).phase==='question'&&(await read(page)).encounters.every(e=>e.questions<=3));
  await context.close();
  const denied=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await denied.route('**/api/quizzes/**',route=>route.abort());
  await denied.addInitScript(()=>{
    const get=Storage.prototype.getItem,set=Storage.prototype.setItem;
    Storage.prototype.getItem=function(...args){if(this===sessionStorage)throw new DOMException('Synthetic storage denial','SecurityError');return get.apply(this,args);};
    Storage.prototype.setItem=function(...args){if(this===sessionStorage)throw new DOMException('Synthetic storage denial','SecurityError');return set.apply(this,args);};
  });
  denied.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  denied.on('request',req=>{if(req.method()==='POST')posts.push(req.url());});
  page=await denied.newPage();await page.goto(base);await page.locator('#start-button').click();
  for(const dir of ['down','down','down','down','right','right','right']){await page.locator(`[data-direction="${dir}"]`).click();await page.evaluate(()=>window.advanceTime(900));}
  await page.screenshot({path:`${output}/denied-storage-question.png`,fullPage:true});
  check('storage denial warns inside the active question instead of falsely claiming progress is saved',await page.locator('#game-dialog .dialog-save-warning').isVisible()&&!(await page.locator('#encounter-menu').innerText()).includes('ההתקדמות נשמרת'));
  await page.locator('#encounter-menu').click();
  check('pause menu honestly explains that leaving or reloading may lose unsaved progress',(await page.locator('#dialog-content').innerText()).includes('אינה נשמרת'));
  await page.locator('#resume-button').click();
  check('unavailable storage never blocks continuing the current in-memory question',(await read(page)).phase==='question'&&await page.locator('[data-choice]').first().isEnabled());
  await denied.close();
  const key='prepx-shadow-maze-session-v1';
  const content=normalizeMazeContent(snapshot.quizzes[0]),old=createState(content.questions,()=>.999999),question=content.questions.find(q=>q.id===old.order[0]);
  old.answers[question.id]={choice:question.correct,correct:true};old.coins=10;
  const blob=JSON.stringify({content,state:old});
  const readFailed=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await readFailed.route('**/api/quizzes/**',r=>r.abort());
  readFailed.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  readFailed.on('request',req=>{if(req.method()==='POST')posts.push(req.url());});
  await readFailed.addInitScript(({key,blob})=>{
    if(!['http:','https:'].includes(location.protocol))return;
    const get=Storage.prototype.getItem,set=Storage.prototype.setItem;
    if(!get.call(sessionStorage,key))set.call(sessionStorage,key,blob);
    window.__qaReadStored=()=>get.call(sessionStorage,key);
    if(new URL(location.href).searchParams.has('read-fault'))Storage.prototype.getItem=function(k){if(this===sessionStorage&&k===key)throw new DOMException('Read-only fault','SecurityError');return get.call(this,k);};
  },{key,blob});
  page=await readFailed.newPage();const faultUrl=new URL(base);faultUrl.searchParams.set('read-fault','1');await page.goto(faultUrl.href);await page.locator('#start-button').click();
  check('read failure with working writes never overwrites a previously earned answer and ten coins',await page.evaluate(()=>window.__qaReadStored())===blob);
  check('read-failure fallback explicitly stays in unsaved in-memory mode',(await read(page)).storageAvailable===false);
  await page.goto(base);await page.locator('#start-button').click();
  check('after reads recover the untouched original expedition restores its earned progress',(await read(page)).coins===10&&(await read(page)).progress.answered===1);
  await readFailed.close();
  const corrupt=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await corrupt.route('**/api/quizzes/**',r=>r.abort());corrupt.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  corrupt.on('request',req=>{if(req.method()==='POST')posts.push(req.url());});
  const broken='{"unrecoverable":';
  await corrupt.addInitScript(({key,broken})=>{if(['http:','https:'].includes(location.protocol)&&!sessionStorage.getItem(key))sessionStorage.setItem(key,broken);},{key,broken});
  page=await corrupt.newPage();await page.goto(base);await page.locator('#new-expedition-button').click();
  await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).started===true);
  check('corrupt save offers a separate playable expedition instead of endless retries',(await read(page)).phase==='explore');
  const backup=await page.evaluate(key=>Object.keys(sessionStorage).filter(k=>k.startsWith(key+'-unrestorable-')).map(k=>sessionStorage.getItem(k)),key);
  check('starting a separate expedition preserves the exact corrupt original in a verified backup',backup.includes(broken));
  await page.reload();await page.locator('#start-button').click();
  check('the separate expedition remains resumable without returning to the corrupt-save loop',(await read(page)).phase==='explore');
  await page.screenshot({path:`${output}/corrupt-save-separate-expedition.png`,fullPage:true});
  await corrupt.close();
  check('critic flows produce no application errors or result writes',!errors.length&&!posts.length);
  await writeFile(`${output}/report.json`,JSON.stringify({base,count:checks.length,checks,errors,posts},null,2));
} catch(error) {
  if(page)await page.screenshot({path:`${output}/failure.png`,fullPage:true}).catch(()=>{});
  await writeFile(`${output}/report.json`,JSON.stringify({base,count:checks.length,checks,errors,posts,failure:error.message},null,2));
  throw error;
} finally { await browser.close(); }
